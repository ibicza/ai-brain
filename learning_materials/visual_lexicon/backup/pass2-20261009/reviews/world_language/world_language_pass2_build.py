def roles(words):
    return {w: ('symbol' if w in SYMBOLS else 'diagram' if w in DIAGRAMS else
                'decoration-or-story' if w in {'узор','сказочный персонаж','силуэт'} else
                'scene-object-overview-only') for w in words}

def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()

def read(path):
    return json.loads(Path(path).read_text(encoding='utf-8'))

def save(name, data):
    (OUT / name).write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf-8', newline='\n')

def main():
    plan = read(OUT / 'index-plan.json')['index']
    manual = read(OUT / 'visual-page-inventory.json')
    manifest = read(REPO / 'learning_materials/belarus_primary/manifest.json')
    books = {b['sha256']:b for b in manifest['books']}
    selected = [s for s in plan if s['original_sha256'][:16] in BOOK_PREFIXES]
    assert {str(s['sheet_index']) for s in selected} == set(manual), 'missing or extra manual sheet'
    assert len(selected) == 60 and sum(len(s['pdf_pages']) for s in selected) == 690
    catalogue = read(MERGE)['words']
    names = defaultdict(list)
    aliases = defaultdict(list)
    for row in catalogue:
        names[row[1].strip().casefold()].append(row)
        if row[4]:
            for a in str(row[4]).split(';'):
                aliases[a.strip().casefold()].append(row)
    pages, observed, seen_media = [], defaultdict(list), defaultdict(list)
    book_pages = defaultdict(list)
    notes = ('Контактный обзор: целая страница содержит объект; точное выделение и все подписи не проверены. '
             'Для таксона возможна опора на печатную подпись, это не независимое распознавание вида. '
             'Сказочные, декоративные и учебные изображения не являются эталоном естественного вида. '
             'Текст на странице не удалён; label leakage не исключён. Требуется согласование пользователя.')
    for sheet in selected:
        assert sha(sheet['media_path']) == sheet['media_sha256']
        vals = manual[str(sheet['sheet_index'])]
        assert len(vals) == len(sheet['pdf_pages'])
        prefix = sheet['original_sha256'][:16]
        for number, value in zip(sheet['pdf_pages'], vals):
            rp = CORPUS / 'books' / prefix / 'records' / f'{number:04d}.json'
            correction = CORPUS / 'geometry-corrections' / prefix / 'records' / f'{number:04d}.json'
            if correction.exists():
                rp = correction
            rec = read(rp)
            assert rec['original_sha256'] == sheet['original_sha256']
            assert rec['original_filename'] == sheet['original_filename'] and rec['pdf_page'] == number
            preview = rec['page_preview']
            image_path = (CORPUS / preview['path']).resolve()
            assert sha(image_path) == preview['sha256']
            words = [RENAMES.get(w.strip(),w.strip()) for w in value.split(',') if w.strip() not in {'TEXT','BLANK','UNKNOWN'}]
