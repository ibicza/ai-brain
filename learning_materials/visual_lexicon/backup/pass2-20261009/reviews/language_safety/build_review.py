def record(key, page):
    pid = f'{key}-p{page:04d}'
    relative = replacements.get(pid, {}).get('corrected_record', f'books/{key}/records/{page:04d}.json')
    path = ROOT / relative
    r = json.loads(path.read_text(encoding='utf-8'))
    assert r['page_id'] == pid and r['pdf_page'] == page
    if pid in replacements:
        assert sha(path) == replacements[pid]['corrected_record_sha256']
    asset = ROOT / r['page_preview']['path']
    assert sha(asset) == r['page_preview']['sha256']
    return r

